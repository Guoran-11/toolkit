/**
 * 找出距给定坐标最近的若干参考地点。
 * @param {number} lat
 * @param {number} lon
 * @param {number} [limit]
 * @returns {Array<{name:string, lat:number, lon:number, distanceKm:number, kind:string}>}
 */
export function nearestPlaces(lat, lon, limit = 3) {
  const latN = Number(lat);
  const lonN = Number(lon);
  if (!Number.isFinite(latN) || !Number.isFinite(lonN)) return [];
  const toRad = (x) => x * Math.PI / 180;
  const cosLat = Math.cos(toRad(latN));
  const scored = PLACES.map((p) => {
    // 先用平面近似做粗排（足够快），再对候选算精确大圆距离
    const dx = (p.lon - lonN) * cosLat;
    const dy = p.lat - latN;
    return { place: p, rough: dx * dx + dy * dy };
  }).sort((a, b) => a.rough - b.rough).slice(0, Math.max(limit * 3, 9));

  const haversine = (lat1, lon1, lat2, lon2) => {
    const dLat = toRad(lat2 - lat1);
    const dLon = toRad(lon2 - lon1);
    const a = Math.sin(dLat / 2) ** 2
      + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
    return 2 * 6371.0088 * Math.asin(Math.min(1, Math.sqrt(a)));
  };

  return scored
    .map(({ place }) => ({
      name: place.name,
      lat: place.lat,
      lon: place.lon,
      kind: place.kind,
      distanceKm: haversine(latN, lonN, place.lat, place.lon),
    }))
    .sort((a, b) => a.distanceKm - b.distanceKm)
    .slice(0, limit);
}

